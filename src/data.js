/** '예' 개수 → 구간 번호(0~3) */
export function bandIndex(area, yes) {
  for (let i = 0; i < area.bands.length; i++) {
    const [min, max] = area.bands[i];
    if (yes >= min && yes <= max) return i;
  }
  return 0;
}

/** 구간 표시 문구: '5~7개' / '8개 이상' */
export function bandRange(area, i) {
  const [min, max] = area.bands[i];
  return max >= 99 ? `${min}개 이상` : `${min}~${max}개`;
}
